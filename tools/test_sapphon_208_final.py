#!/usr/bin/env python3
"""SAPPHON-208 original bytes and eight-source freeze negative controls."""
import importlib.util,io,json,pathlib,tempfile,unittest,zipfile
p=pathlib.Path(__file__).with_name("sapphon_208_final.py")
spec=importlib.util.spec_from_file_location("freeze208",p)
m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
def fixture(image=False):
 files=[("pkg/lib.rs",b"fn main(){}"),("pkg/.cargo-checksum.json",b"{}")]
 tar=m.vendor.pack(files)
 rows=[{"path":n,"bytes":len(b),"sha256":m.sha(b)} for n,b in files]
 lock=b"# This file is automatically @generated by Cargo.\nversion = 4\n"
 report=m.vendor.hold("SOURCE_OWNED_VENDOR_TREE_VERIFIED",
   files=2,entries=rows,tree_sha256=m.sha(m.vendor.canonical(rows)),
   archive_sha256=m.sha(tar),lock_sha256=m.sha(lock),offline_check_observed=True)
 summary={"schema":"sapphon-207-source-owned-run-v1","commit":m.SOURCE,
  "run_id":"207","attempt":"2","recovery_authorized":False,
  "steps":{"VENDOR":"success","IMAGE":"success" if image else "failure"},
  "offline_check_observed":True,
  "vendor_tree_sha256":report["tree_sha256"],
  "vendor_archive_sha256":report["archive_sha256"],
  "built_image_archive_sha256":None,"built_image_local_id":None}
 items={"207-Cargo.lock":lock,"207-vendor.tar":tar,
  "207-vendor.json":report,"207-summary.json":summary}
 if image:
  imagebytes=b"docker export fixture"
  summary["built_image_archive_sha256"]=m.sha(imagebytes)
  summary["built_image_local_id"]="sha256:"+"e"*64
  items.update({"207-image.tar":imagebytes,
    "207-image-report.json":{"schema":"sapphon-207-local-image-v1",
      "archive_sha256":m.sha(imagebytes),"built_image_local_id":summary["built_image_local_id"],
      "recovery_authorized":False},
    "207-image.sha256":(m.sha(imagebytes)+"  207-image.tar\n").encode()})
 return items
def pack(items):
 data=io.BytesIO()
 with zipfile.ZipFile(data,"w") as z:
  for k,v in items.items():z.writestr(k,v if isinstance(v,bytes) else json.dumps(v))
 return data.getvalue()
def inspect(items=None):return m.inspect_artifact(pack(fixture() if items is None else items),{"id":207,"run_attempt":2})
class Tests(unittest.TestCase):
 def test_owned_vendor_replayed(self):
  r=inspect();self.assertTrue(r["vendor_archive_verified"])
  self.assertFalse(r["image_archive_verified"] or r["recovery_authorized"])
 def test_owned_image_replayed(self):
  r=inspect(fixture(True));self.assertTrue(r["image_archive_verified"])
  self.assertFalse(r["recovery_authorized"])
 def test_missing_original_zip(self):
  self.assertEqual(m.inspect_artifact(None,{"id":207,"run_attempt":2})["state"],"ORIGINAL_ZIP_UNAVAILABLE_OR_OVERSIZE")
 def test_missing_vendor_member(self):
  v=fixture();v.pop("207-vendor.tar")
  self.assertEqual(inspect(v)["state"],"UNSAFE_OR_DUPLICATE_ARTIFACT")
 def test_wrong_run_attempt(self):
  v=fixture();v["207-summary.json"]["attempt"]="3"
  self.assertEqual(inspect(v)["state"],"ORIGINAL_RUN_ATTEMPT_CONFLICT")
 def test_wrong_source_sha(self):
  v=fixture();v["207-summary.json"]["commit"]="f"*40
  self.assertEqual(inspect(v)["state"],"ORIGINAL_RUN_ATTEMPT_CONFLICT")
 def test_vendor_archive_mutation(self):
  v=fixture();v["207-vendor.tar"]+=b"changed"
  self.assertIn("ARCHIVE_SHA_CONFLICT",inspect(v)["state"])
 def test_lock_bytes_mutation(self):
  v=fixture();v["207-Cargo.lock"]+=b"changed"
  self.assertEqual(inspect(v)["state"],"LOCKFILE_BYTES_CONFLICT")
 def test_vendor_summary_fork(self):
  v=fixture();v["207-summary.json"]["vendor_tree_sha256"]="f"*64
  self.assertEqual(inspect(v)["state"],"REPORT_SUMMARY_CONFLICT")
 def test_false_success_claim_no_image(self):
  v=fixture();v["207-summary.json"]["steps"]["IMAGE"]="success"
  self.assertEqual(inspect(v)["state"],"MISSING_ORIGINAL_IMAGE_FOR_SUCCESS_CLAIM")
 def test_partial_image(self):
  v=fixture(True);v.pop("207-image.tar")
  self.assertEqual(inspect(v)["state"],"PARTIAL_IMAGE_ARCHIVE")
 def test_image_tar_mutation(self):
  v=fixture(True);v["207-image.tar"]+=b"tamper"
  self.assertEqual(inspect(v)["state"],"ORIGINAL_IMAGE_EVIDENCE_CONFLICT")
 def test_image_receipt_mutation(self):
  v=fixture(True);v["207-image.sha256"]=b"f"*64
  self.assertEqual(inspect(v)["state"],"ORIGINAL_IMAGE_RECEIPT_CONFLICT")
 def test_recovery_claim_rejected(self):
  v=fixture();v["207-summary.json"]["recovery_authorized"]=True
  self.assertEqual(inspect(v)["state"],"ORIGINAL_RUN_ATTEMPT_CONFLICT")
 def test_exact_eight_module_count(self):
  with tempfile.TemporaryDirectory() as d:
   for name in m.MODULES.values():
    p=pathlib.Path(d)/name;p.parent.mkdir(parents=True,exist_ok=True);p.write_text("mod")
   out=m.freeze_sources(d)
   self.assertTrue(out["source_design_complete"])
   self.assertEqual(len(out["source_inventory"]),8)
 def test_missing_eighth_module_refused(self):
  with tempfile.TemporaryDirectory() as d:
   for n,path in list(m.MODULES.items())[:-1]:
    p=pathlib.Path(d)/path;p.parent.mkdir(parents=True,exist_ok=True);p.write_text("mod")
   self.assertEqual(m.freeze_sources(d)["state"],"SOURCE_MODULE_NOT_FOUND")
if __name__=="__main__":unittest.main()
