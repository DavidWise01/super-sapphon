#!/usr/bin/env python3
"""SAPPHON-206 ZIP and hosted-run identity negative controls (synthetic)."""
import importlib.util,io,json,pathlib,unittest,zipfile
p=pathlib.Path(__file__).with_name("sapphon_206_import_lock.py")
s=importlib.util.spec_from_file_location("import206",p)
m=importlib.util.module_from_spec(s);s.loader.exec_module(m)
LOCK=b"# This file is automatically @generated by Cargo.\nversion = 4\n"
def fixture():
 run={"id":205,"run_attempt":2,"head_sha":m.SOURCE}
 art={"id":206,"name":m.ARTIFACT,"expired":False}
 prov={"schema":"sapphon-205-cargo-provenance-v1",
       "source_sha":"50680b739378147d626c4822862d73306acc26bf",
       "offline_verified":True,"lockfile_sha256":m.hashbytes(LOCK),"recovery_authorized":False,
       "packages":15}
 summary={"schema":"sapphon-205-source-owned-run-v1",
   "commit":m.SOURCE,"run_id":"205","attempt":"2","recovery_authorized":False,
   "steps":{k:"success" for k in ("GENERATE","VENDOR","OFFLINE","PROVENANCE")},
   "generated_lock_observed":True,"offline_dependency_check_observed":True,
   "lockfile_sha256":m.hashbytes(LOCK)}
 flags={k:True for k in ("lock_generation","vendor","offline_metadata","offline_check")}
