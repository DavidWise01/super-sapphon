#!/usr/bin/env python3
"""SAPPHON-091 read-only GitHub Actions clock publisher.
Copies previously issued clock outputs; never calculates new time or authorization.
Source: docs/sapphon/source/clock.json. Destination: docs/sapphon/live/clock.json.
"""
import argparse
import hashlib
import json
import math
import re
from pathlib import Path

REGS = ("ymd", "hms", "degree_arcminute_arcsecond", "arc_arc_arc")
FLAGS = ("second", "minute", "day")

def validate(doc):
    if doc.get("schema") != "sapphon-clock-records-v1":
        raise ValueError("Unexpected format")
    if doc.get("mode") != "static-archive":
        raise ValueError("Only recorded archive input is accepted")
    records = doc.get("records")
    if not isinstance(records, list) or not 1 <= len(records) <= 100000:
        raise ValueError("Empty or oversized record batch")
    identities = set()
    for i, record in enumerate(records):
        if type(record.get("seq")) is not int or record["seq"] != i:
            raise ValueError("Noncontiguous or out-of-order event sequence")
        if type(record.get("sector")) is not int or record["sector"] != i % 8:
            raise ValueError("Invalid eight-phase sector")
        h = record.get("hash")
        if not isinstance(h, str) or not re.fullmatch("[0-9a-f]{64}", h) or h in identities:
            raise ValueError("Missing/duplicate/invalid event digest")
        identities.add(h)
        address = record.get("address")
        if not isinstance(address, dict) or set(address) != set(REGS):
            raise ValueError("Invalid four-register address")
        for key in REGS:
            vals = address[key]
            if not isinstance(vals, list) or len(vals) != 3 or any(type(v) is not int for v in vals):
                raise ValueError("Noninteger address component")
        est, unc = record.get("estimate"), record.get("uncertainty")
        if type(est) not in (float, int) or not math.isfinite(est):
            raise ValueError("Invalid estimate")
        if unc is not None and (type(unc) not in (float, int) or not math.isfinite(unc) or unc < 0):
            raise ValueError("Invalid uncertainty")
        for flag in FLAGS:
            if type(record.get(flag)) is not bool:
                raise ValueError("Authorization must be explicitly recorded as boolean")
    return records

def publish(source, dest):
    source_bytes = source.read_bytes()
    doc = json.loads(source_bytes)
    records = validate(doc)
    out = {
        "schema": "sapphon-clock-records-v1",
        "mode": "static-archive",
        "origin": "SAPPHON-082 archived output; generated by SAPPHON-091 publisher",
        "source_sha256": hashlib.sha256(source_bytes).hexdigest(),
        "record_count": len(records),
        "note": "Not live UTC or hardware. Authorization copied, not granted.",
        "records": records,
    }
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(out, indent=2, sort_keys=True) + "\n")
    return out

def tests(path):
    original = json.loads(path.read_text())
    validate(original)
    assert len(original["records"]) >= 8
    assert validate(json.loads(json.dumps(original))) == original["records"]
    def rejection(change):
        d = json.loads(json.dumps(original))
        change(d["records"])
        try: validate(d)
        except (ValueError, KeyError, TypeError): return
        raise AssertionError("Invalid records were accepted")
    rejection(lambda r: r[1].update(seq=3))
    rejection(lambda r: r[2].update(sector=7))
    rejection(lambda r: r[3].update(hash=r[2]["hash"]))
    rejection(lambda r: r[4].update(hash="123"))
    rejection(lambda r: r[5].update(day="yes"))
    rejection(lambda r: r[6].update(address={"ymd": [2026,11,23]}))
    rejection(lambda r: r[7].update(uncertainty=-1))
    print("PASS: 9 checks (2 valid/replay + 7 rejection cases)")

if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--source", type=Path, default=Path("docs/sapphon/source/clock.json"))
    p.add_argument("--output", type=Path, default=Path("docs/sapphon/live/clock.json"))
    p.add_argument("--test", action="store_true")
    args = p.parse_args()
    if args.test: tests(args.source)
    else:
        result = publish(args.source, args.output)
        print("PASS: published", len(result["records"]), "archived, non-live records")
