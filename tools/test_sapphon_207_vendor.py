#!/usr/bin/env python3
"""SAPPHON-207 deterministic vendor archive tests: fixtures are not custody."""
import importlib.util,io,json,pathlib,tarfile,tempfile,unittest
p=pathlib.Path(__file__).with_name("sapphon_207_vendor.py")
s=importlib.util.spec_from_file_location("vendor207",p)
m=importlib.util.module_from_spec(s);s.loader.exec_module(m)
LOCK=b'# This file is automatically @generated by Cargo.\nversion = 4\n'
def sample():
 d=tempfile.TemporaryDirectory();base=pathlib.Path(d.name)
 (base/"serde-1.0").mkdir()
 (base/"serde-1.0"/".cargo-checksum.json").write_text('{"files":{}}')
 (base/"serde-1.0"/"lib.rs").write_text("pub fn test() {}")
 return d,base
class Tests(unittest.TestCase):
 def test_round_trip_and_hold(self):
  d,p=sample()
  try:
   r,files=m.inventory(p,LOCK,True);tar=m.pack(files);r["archive_sha256"]=m.sha(tar)
   checked=m.verify_archive(tar,r)
   self.assertEqual(checked["state"],"ORIGINAL_VENDOR_ARCHIVE_MATCH")
   self.assertFalse(checked["recovery_authorized"])
  finally:d.cleanup()
 def test_inventory_is_stable(self):
  d,p=sample()
  try:
   a,_=m.inventory(p,LOCK,True);b,_=m.inventory(p,LOCK,True)
   self.assertEqual(a["tree_sha256"],b["tree_sha256"])
  finally:d.cleanup()
 def test_mutation_changes_tree(self):
  d,p=sample()
  try:
   a,_=m.inventory(p,LOCK,True)
   (p/"serde-1.0"/"lib.rs").write_text("changed")
   b,_=m.inventory(p,LOCK,True)
   self.assertNotEqual(a["tree_sha256"],b["tree_sha256"])
  finally:d.cleanup()
 def test_symlink_refused(self):
  d,p=sample()
  try:
   (p/"link").symlink_to(p/"serde-1.0"/"lib.rs")
   r,_=m.inventory(p,LOCK,True)
   self.assertEqual(r["state"],"VENDOR_BYTES_INVALID")
  finally:d.cleanup()
 def test_missing_lock(self):
  d,p=sample()
  try:self.assertEqual(m.inventory(p,b"",True)[0]["state"],"ORIGINAL_LOCK_MISSING")
  finally:d.cleanup()
 def test_offline_check_is_required(self):
  d,p=sample()
  try:self.assertEqual(m.inventory(p,LOCK,False)[0]["state"],"OFFLINE_COMPILATION_NOT_OBSERVED")
  finally:d.cleanup()
 def test_archive_byte_fork(self):
  d,p=sample()
  try:
   r,files=m.inventory(p,LOCK,True);tar=m.pack(files)
   r["archive_sha256"]="f"*64
   self.assertEqual(m.verify_archive(tar,r)["state"],"ARCHIVE_SHA_CONFLICT")
  finally:d.cleanup()
 def test_archive_report_fork(self):
  d,p=sample()
  try:
   r,files=m.inventory(p,LOCK,True);tar=m.pack(files);r["archive_sha256"]=m.sha(tar)
   r["entries"][0]["sha256"]="f"*64
   self.assertEqual(m.verify_archive(tar,r)["state"],"TREE_SHA_CONFLICT")
  finally:d.cleanup()
 def test_unsafe_tar_symlink_denied(self):
  out=io.BytesIO()
  with tarfile.open(fileobj=out,mode="w") as t:
   x=tarfile.TarInfo("foo");x.type=tarfile.SYMTYPE;x.linkname="../../bad";t.addfile(x)
  r=m.hold("SOURCE_OWNED_VENDOR_TREE_VERIFIED",archive_sha256=m.sha(out.getvalue()),files=1)
  self.assertEqual(m.verify_archive(out.getvalue(),r)["state"],"ARCHIVE_MEMBER_UNSAFE")
 def test_archive_missing(self):
  self.assertEqual(m.verify_archive(b"",{})["state"],"ARCHIVE_BYTES_NOT_OBSERVED")
 def test_image_mutable_tag_denied(self):
  r=m.hold("ORIGINAL_VENDOR_ARCHIVE_MATCH")
  self.assertEqual(m.image_gate("rust:latest",{},r)["state"],"IMAGE_REFERENCE_NOT_PINNED")
 def test_image_no_repo_digest(self):
  r=m.hold("ORIGINAL_VENDOR_ARCHIVE_MATCH")
  image="docker.io/library/rust@sha256:"+"a"*64
  self.assertEqual(m.image_gate(image,{"Id":"sha256:"+"b"*64,"RepoDigests":[]},r)["state"],"IMAGE_REPOSITORY_DIGEST_NOT_OBSERVED")
 def test_matching_image_still_hold(self):
  image="docker.io/library/rust@sha256:"+"a"*64
  r=m.hold("ORIGINAL_VENDOR_ARCHIVE_MATCH",files=2,tree_sha256="b"*64,
    archive_sha256="c"*64,lock_sha256="d"*64)
  out=m.image_gate(image,{"Id":"sha256:"+"e"*64,"RepoDigests":[image]},r)
  self.assertTrue(out["image_digest_verified"])
  self.assertFalse(out["recovery_authorized"])
 def test_image_without_vendor_denied(self):
  image="docker.io/library/rust@sha256:"+"a"*64
  self.assertEqual(m.image_gate(image,{},m.hold("VENDOR_MISSING"))["state"],"VENDOR_ARCHIVE_NOT_VERIFIED")
 def test_empty_vendor_denied(self):
  with tempfile.TemporaryDirectory() as d:
   self.assertEqual(m.inventory(d,LOCK,True)[0]["state"],"VENDOR_BYTES_INVALID")
 def test_archive_deterministic(self):
  d,p=sample()
  try:
   _,files=m.inventory(p,LOCK,True)
   self.assertEqual(m.pack(files),m.pack(files))
  finally:d.cleanup()
if __name__=="__main__":unittest.main()
