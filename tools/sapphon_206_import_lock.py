#!/usr/bin/env python3
"""SAPPHON-206 original hosted Cargo.lock acquisition; never fabricate source bytes.

Searches exact source SHA / run-attempt / artifact and compares raw lock bytes to
original 205 provenance AND summary. No auto-commit and no role elevation.
"""
import argparse,hashlib,importlib.util,io,json,pathlib,stat,subprocess,sys,zipfile
ROOT=pathlib.Path(__file__).resolve().parent
spec=importlib.util.spec_from_file_location("api194_206",ROOT/"sapphon_194_acquire.py")
api=importlib.util.module_from_spec(spec);spec.loader.exec_module(api)
SOURCE="a73488b1cbfa353d7a2e0d0bd762f7402f7117ee"
WORKFLOW="sapphon-205-lock-genesis.yml"
ARTIFACT="sapphon-205-cargo-lock-and-offline-provenance"
REQUIRED={"Cargo.lock","205-metadata.json","205-checks.json","205-provenance.json","205-summary.json"}
MAX_ZIP=32*1024*1024
def hashbytes(b):return hashlib.sha256(b).hexdigest()
def hold(state,**extra):
 return {"schema":"sapphon-206-lock-import-v1","state":state,
  "source_sha":SOURCE,"original_lock_observed":False,
  "lockfile_sha256":None,"source_promotable":False,
  "source_committed":False,"offline_container_qualified":False,
  "original_image_digest":None,"independent_witnesses":0,
  "external_custody_authenticated":False,"authenticated_utc":False,
  "global_anti_rollback_authenticated":False,"recovery_authorized":False,
  "lock_cleared":False,"decision":"PHASE_XX_LOCK_IMPORT_HOLD",**extra}
def inspect(raw,run,art):
 if type(raw) is not bytes or not raw or len(raw)>MAX_ZIP:return hold("ARTIFACT_ZIP_NOT_OBSERVED")
 try:
  with zipfile.ZipFile(io.BytesIO(raw)) as z:
   infos=z.infolist();names=[f.filename for f in infos]
   if len(names)!=len(set(names)) or not REQUIRED.issubset(set(names)) or any(
      f.is_dir() or f.flag_bits&1 or f.file_size>8*1024*1024 or
      stat.S_ISLNK(f.external_attr>>16) or "/" in f.filename or "\\" in f.filename
      for f in infos):return hold("ZIP_MEMBERS_UNTRUSTED")
   lock=z.read("Cargo.lock")
   prov=json.loads(z.read("205-provenance.json"))
   summary=json.loads(z.read("205-summary.json"))
   flags=json.loads(z.read("205-checks.json"))
   meta=json.loads(z.read("205-metadata.json"))
 except (zipfile.BadZipFile,KeyError,ValueError,RuntimeError,UnicodeError,OverflowError):
  return hold("ZIP_CORRUPT")
 if type(prov) is not dict or prov.get("schema")!="sapphon-205-cargo-provenance-v1":
  return hold("PROVENANCE_SCHEMA_INVALID")
 if type(summary) is not dict or summary.get("schema")!="sapphon-205-source-owned-run-v1":
  return hold("SUMMARY_SCHEMA_INVALID")
 if (summary.get("commit")!=SOURCE or str(summary.get("run_id"))!=str(run["id"])
   or str(summary.get("attempt"))!=str(run["run_attempt"])
   or summary.get("recovery_authorized") is not False
   or prov.get("source_sha")!="50680b739378147d626c4822862d73306acc26bf"
   or prov.get("recovery_authorized") is not False):
  return hold("ORIGINAL_RUN_ATTEMPT_CONFLICT")
 if (summary.get("steps",{}).get("GENERATE")!="success" or
  summary.get("steps",{}).get("VENDOR")!="success" or
  summary.get("steps",{}).get("OFFLINE")!="success" or
  summary.get("steps",{}).get("PROVENANCE")!="success"):
  return hold("HOSTED_DEPENDENCY_STEPS_NOT_PASS")
 if (prov.get("offline_verified") is not True or
     summary.get("offline_dependency_check_observed") is not True or
     summary.get("generated_lock_observed") is not True):
  return hold("OFFLINE_HOSTED_QUALIFICATION_MISSING")
 if type(flags) is not dict or set(flags)!={"lock_generation","vendor","offline_metadata","offline_check"} or any(v is not True for v in flags.values()):
  return hold("OFFLINE_STEP_RECEIPTS_MISSING")
 if type(meta) is not dict or type(meta.get("packages")) is not list:
  return hold("METADATA_MISSING")
 if not lock or len(lock)>8*1024*1024 or not lock.startswith(b"# This file is automatically @generated by Cargo."):
  return hold("LOCK_BYTES_INVALID")
 value=hashbytes(lock)
 if prov.get("lockfile_sha256")!=value or summary.get("lockfile_sha256")!=value:
  return hold("LOCK_SHA256_EQUIVOCATION",observed_lockfile_sha256=value)
 return {**hold("GITHUB_OWNED_LOCK_BYTES_MATCH"),
  "original_lock_observed":True,"lockfile_sha256":value,
  "source_promotable":True,"original_zip_sha256":hashbytes(raw),
  "run_id":run["id"],"attempt":run["run_attempt"],
  "artifact_id":art["id"],"packages_reported":prov.get("packages"),
  "lock_bytes":lock}
def acquire(fetch=api.json_api,download=api.api):
 root=f"repos/{api.REPO}/actions"
 runs,state,_=api.listing(f"{root}/workflows/{WORKFLOW}/runs","workflow_runs",fetch)
 if state!="EXHAUSTED":return hold("RUN_LIST_"+state)
 selected=[r for r in runs if r.get("head_sha")==SOURCE]
 if not selected:return hold("EXACT_205_RUN_NOT_OBSERVED")
 if any(not api.positive(x.get("run_attempt")) for x in selected):
  return hold("RUN_ATTEMPT_INVALID")
 run=max(selected,key=lambda x:(x["id"],x["run_attempt"]))
 arts,state,_=api.listing(f"{root}/runs/{run['id']}/artifacts","artifacts",fetch)
 if state!="EXHAUSTED":return hold("ARTIFACT_LIST_"+state)
 found=[a for a in arts if a.get("name")==ARTIFACT]
 if len(found)!=1:return hold("ARTIFACT_MISSING_OR_DUPLICATE")
 art=found[0]
 if art.get("expired") is not False:return hold("ARTIFACT_EXPIRED_OR_UNKNOWN")
 origin=art.get("workflow_run") or {}
 if origin and (origin.get("id")!=run["id"] or origin.get("head_sha")!=SOURCE):
  return hold("ARTIFACT_ANCESTRY_MISMATCH")
 try:blob=download(f"{root}/artifacts/{art['id']}/zip")
 except (OSError,subprocess.CalledProcessError,subprocess.TimeoutExpired):
  return hold("ARTIFACT_DOWNLOAD_UNAVAILABLE")
 return inspect(blob,run,art)
def main():
 p=argparse.ArgumentParser();p.add_argument("--out",default="qualification-artifact/206-import.json")
 p.add_argument("--lock-out",default="qualification-artifact/206-Cargo.lock")
 opt=p.parse_args()
 try:result=acquire()
 except (OSError,KeyError,ValueError,TypeError,subprocess.CalledProcessError,subprocess.TimeoutExpired) as e:
  result=hold("READBACK_UNAVAILABLE",error_type=type(e).__name__)
 lock=result.pop("lock_bytes",None)
 dest=pathlib.Path(opt.out);dest.parent.mkdir(parents=True,exist_ok=True)
 dest.write_text(json.dumps(result,sort_keys=True,indent=2)+"\n")
 if lock is not None:
  with pathlib.Path(opt.lock_out).open("xb") as f:
   f.write(lock);f.flush()
   import os
   os.fsync(f.fileno())
 print(result["state"],result["lockfile_sha256"])
 if not result["source_promotable"]:sys.exit(1)
if __name__=="__main__":main()
