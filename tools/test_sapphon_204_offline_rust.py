#!/usr/bin/env python3
"""SAPPHON-204 offline Rust replay safety and missing-lock negative controls."""
import importlib.util,pathlib,tempfile,unittest
p=pathlib.Path(__file__).with_name("sapphon_204_offline_rust.py")
s=importlib.util.spec_from_file_location("offline204",p)
m=importlib.util.module_from_spec(s);s.loader.exec_module(m)
def failure():
 return {"state":"OBSERVED_SOURCE_FAILURE","original_bytes_complete":True,
  "replay_executed":False,"run_id":201,"attempt":2,
  "original_log_sha256":"a"*64,"original_artifact_sha256":"b"*64,
  "observed_201_failures":[{"step":"rust","conclusion":"failure"}]}
def lock():
 return {"state":"LOCK_BYTES_PINNED","lockfile_sha256":"d"*64}
def image():return "sha256:"+"c"*64
class Tests(unittest.TestCase):
 def test_no_cargo_lock_denied(self):
  with tempfile.TemporaryDirectory() as d:
   self.assertEqual(m.lock_preflight(d)["state"],"CARGO_LOCK_NOT_PRESENT")
 def test_manifest_not_lock(self):
  with tempfile.TemporaryDirectory() as d:
   path=pathlib.Path(d)/"rust/sapphon-liveness";path.mkdir(parents=True)
   (path/"Cargo.toml").write_text("[package]\nname='x'\n")
   self.assertEqual(m.lock_preflight(d)["state"],"CARGO_LOCK_NOT_PRESENT")
 def test_locked_bytes_must_match(self):
  with tempfile.TemporaryDirectory() as d:
   path=pathlib.Path(d)/"Cargo.lock"
   path.write_text("# This file is automatically @generated by Cargo.\nversion = 4\n")
   self.assertEqual(m.lock_preflight(d)["state"],"LOCK_DIGEST_UNPINNED_OR_MISMATCH")
   actual=m.sha(path.read_bytes())
   self.assertEqual(m.lock_preflight(d,actual)["state"],"LOCK_BYTES_PINNED")
 def test_unknown_digest_denied(self):
  self.assertEqual(m.qualified(failure(),m.RUST_SOURCE,"rust:latest",lock(),True)["state"],"IMAGE_DIGEST_UNPINNED")
 def test_no_genuine_failure(self):
  f=failure();f["state"]="NOT_OBSERVED"
  self.assertEqual(m.qualified(f,m.RUST_SOURCE,image(),lock(),True)["state"],"NO_ACTUAL_RUST_FAILURE")
 def test_wrong_source_revision(self):
  self.assertEqual(m.qualified(failure(),"0"*40,image(),lock(),True)["state"],"WRONG_PINNED_SOURCE")
 def test_no_original_bytes(self):
  f=failure();f["original_bytes_complete"]=False
  self.assertEqual(m.qualified(f,m.RUST_SOURCE,image(),lock(),True)["state"],"ORIGINAL_BYTES_NOT_QUALIFIED")
 def test_not_rust_failure(self):
  f=failure();f["observed_201_failures"]=[{"step":"python","conclusion":"failure"}]
  self.assertEqual(m.qualified(f,m.RUST_SOURCE,image(),lock(),True)["state"],"NO_FAILED_RUST_STEP")
 def test_missing_lock_blocks(self):
  self.assertEqual(m.qualified(failure(),m.RUST_SOURCE,image(),{"state":"CARGO_LOCK_NOT_PRESENT"},True)["state"],"CARGO_LOCK_NOT_QUALIFIED")
 def test_no_verified_image_preflight(self):
  self.assertEqual(m.qualified(failure(),m.RUST_SOURCE,image(),lock(),False)["state"],"OFFLINE_IMAGE_NOT_QUALIFIED")
 def test_eligible_does_not_execute(self):
  x=m.qualified(failure(),m.RUST_SOURCE,image(),lock(),True)
  self.assertTrue(x["replay_eligible"]);self.assertFalse(x["replay_executed"])
  self.assertFalse(x["recovery_authorized"])
 def test_docker_no_network_and_pull(self):
  cmd=m.docker_argv("/tmp/readonly-replay",image())
  self.assertIn("none",cmd);self.assertIn("never",cmd)
  self.assertIn("--read-only",cmd);self.assertIn("--locked",cmd)
  self.assertIn("--offline",cmd)
  self.assertNotIn("sh",cmd)
 def test_mutable_tag_not_allowed(self):
  with self.assertRaises(ValueError):m.docker_argv("/tmp","rust:latest")
 def test_ineligible_never_executes(self):
  f=m.hold("NOT_OBSERVED")
  self.assertFalse(m.run_replay(f,"/tmp")["replay_executed"])
 def test_rust_image_not_assumed_present(self):
  f=m.qualified(failure(),m.RUST_SOURCE,image(),lock(),False)
  self.assertFalse(f["replay_eligible"])
 def test_invalid_lock_header(self):
  with tempfile.TemporaryDirectory() as d:
   (pathlib.Path(d)/"Cargo.lock").write_text("not a lockfile")
   self.assertEqual(m.lock_preflight(d)["state"],"CARGO_LOCK_HEADER_INVALID")
if __name__=="__main__":unittest.main()
